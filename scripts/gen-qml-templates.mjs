#!/usr/bin/env node
// Copies WhisperBox's shared form templates (whisperbox-sdk templates/templates.mjs, mounted in
// mobile/src/whisperbox) into a plain QML JavaScript library for the desktop view, so both apps
// offer exactly the same forms (ADR 0005). QML can't import an ES module, hence the copy.
//   node scripts/gen-qml-templates.mjs           write freequencies-ui/qml/templates.js
//   node scripts/gen-qml-templates.mjs --check   fail if it is out of date (run by mobile npm test)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { TEMPLATES } = await import(join(root, "mobile/src/whisperbox/templates/templates.mjs"));
const out = join(root, "freequencies-ui/qml/templates.js");
const js = `// GENERATED by scripts/gen-qml-templates.mjs from whisperbox-sdk templates/templates.mjs.
// Do not edit: change the SDK, bump the submodule, run the script.
.pragma library

var TEMPLATES = ${JSON.stringify(TEMPLATES, null, 2)};

// A fresh copy of a template with fields overridden (title, description, ...).
function template(name, overrides) {
    var t = TEMPLATES[name];
    if (!t) throw new Error("unknown template: " + name);
    var copy = JSON.parse(JSON.stringify(t));
    for (var k in (overrides || {})) copy[k] = overrides[k];
    return copy;
}
`;
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(out, "utf8"); } catch { /* missing */ }
  if (cur !== js) { console.error("freequencies-ui/qml/templates.js is out of date: run node scripts/gen-qml-templates.mjs"); process.exit(1); }
  console.log("QML TEMPLATES OK");
} else {
  writeFileSync(out, js);
  console.log("wrote " + out);
}
